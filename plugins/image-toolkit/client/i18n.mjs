/** Return the only supported UI language. */
export function detectLang() {
	return "en";
}

/** Translate a key using the English dictionary. */
export function makeT(_getLang) {
	return (key, vars) => {
		let s = DICT.en[key] ?? key;
		if (vars) {
			for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
		}
		return s;
	};
}
